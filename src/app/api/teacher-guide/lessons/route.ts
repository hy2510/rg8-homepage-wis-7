import {
  RouteResponse,
  executeRequestAction,
  getParameters,
} from '@/app/api/_util'
import { getAuthorizationWithCookie } from '@/authorization/server/nextjsCookieAuthorization'
import { NextRequest } from 'next/server'
import TeacherGuide from '@/repository/server/teacherguide'

export async function GET(request: NextRequest) {
  const authorizationWithCookie = await getAuthorizationWithCookie()
  const token = authorizationWithCookie.getActiveAccessToken()

  if (!token) {
    return RouteResponse.invalidAccessToken()
  }

  const userDetails = token
    ? authorizationWithCookie.getTokenUserDetails()
    : undefined
  const isStaffAccess =
    userDetails?.role === 'staff' || userDetails?.role === 'admin'

  if (!isStaffAccess) {
    return RouteResponse.response(null, { status: 403 })
  }

  const parameter = await getParameters(request, 'teacherCurriculumId')
  const teacherCurriculumId = parameter.getNumber('teacherCurriculumId', 0)

  const [payload, status, error] = await executeRequestAction(
    TeacherGuide.lessonList(token, { teacherCurriculumId }),
  )

  if (status.status >= 200 && status.status < 300) {
    const newPayload = {
      lessons: payload?.lessons?.map((item: any) => {
        if (
          (item.ActivityType === 'activity' &&
            item.ActivityGroup === 'Activity') ||
          (item.ActivityType === 'read' && item.ActivityGroup === 'eBook')
        ) {
          const studyInfo = findStudyIdAndStudentHistoryId(item.LevelRoundId)
          if (studyInfo) {
            return {
              ...item,
              StudyId: studyInfo.StudyId,
              StudentHistoryId: studyInfo.StudentHistoryId,
            }
          }
        }
        return item
      }),
    }
    console.log('newPayload', newPayload)
    return RouteResponse.response(newPayload, status)
  }
  if (error) {
    return RouteResponse.commonError()
  }
  return RouteResponse.commonError()
}

function findStudyIdAndStudentHistoryId(levelRoundId: string):
  | {
      StudyId: string
      StudentHistoryId: string
    }
  | undefined {
  const studyInfo = STUDY_POOL.find(
    (item) => item.levelRoundId === Number(levelRoundId),
  )
  if (studyInfo) {
    return {
      StudyId: studyInfo.studyId,
      StudentHistoryId: studyInfo.studentHistoryId,
    }
  }
  return undefined
}

